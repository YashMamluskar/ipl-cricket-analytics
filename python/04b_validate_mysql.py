"""
Phase 4b - Validate the loaded MySQL database
=============================================

1. Inventory of what exists on the server (tables + row counts, primary/foreign keys,
   indexes, views) read from information_schema.
2. Executes every check in sql/05_data_quality_checks.sql (each returns PASS/FAIL).

Outputs: reports/sql_validation_report.md, reports/sql_validation_checks.csv
Run from the project root (after 04_load_mysql.py):
    python python/04b_validate_mysql.py
"""
from __future__ import annotations

import sys
from datetime import datetime
from importlib import import_module
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ipl_config as cfg  # noqa: E402
import mysql_utils as mu  # noqa: E402

md_table = import_module("01_data_profiling").md_table


def inventory(conn) -> dict:
    q = {
        "tables": """SELECT table_name, table_type, table_rows AS approx_rows_from_stats
                     FROM information_schema.tables WHERE table_schema = DATABASE() ORDER BY table_type, table_name""",
        "foreign_keys": """SELECT table_name, constraint_name, referenced_table_name
                           FROM information_schema.referential_constraints WHERE constraint_schema = DATABASE()
                           ORDER BY table_name, constraint_name""",
        "indexes": """SELECT table_name, index_name, GROUP_CONCAT(column_name ORDER BY seq_in_index) AS columns_,
                             MAX(non_unique) AS non_unique
                      FROM information_schema.statistics WHERE table_schema = DATABASE()
                      GROUP BY table_name, index_name ORDER BY table_name, index_name""",
        "check_constraints": """SELECT tc.table_name, cc.constraint_name
                                FROM information_schema.check_constraints cc
                                JOIN information_schema.table_constraints tc
                                  ON tc.constraint_name = cc.constraint_name AND tc.constraint_schema = cc.constraint_schema
                                WHERE cc.constraint_schema = DATABASE() ORDER BY 1, 2""",
    }
    out = {k: mu.query_df(conn, s) for k, s in q.items()}
    # exact row counts (information_schema.table_rows is only an estimate for InnoDB)
    base = out["tables"][out["tables"].TABLE_TYPE == "BASE TABLE"].TABLE_NAME
    out["row_counts"] = pd.DataFrame([(t, int(mu.query_df(conn, f"SELECT COUNT(*) AS n FROM `{t}`").n[0])) for t in base],
                                     columns=["table", "exact_rows"])
    return out


def run_checks(conn) -> pd.DataFrame:
    stmts = [s for s in mu.split_sql((mu.SQL_DIR / "05_data_quality_checks.sql").read_text(encoding="utf-8"))
             if not s.upper().startswith("USE ")]
    frames = []
    for s in stmts:
        df = mu.query_df(conn, s)
        df.columns = ["check_id", "area", "check_name", "expected", "actual", "status"]
        frames.append(df)
    return pd.concat(frames, ignore_index=True)


def main():
    conn = mu.connect()
    info = mu.describe_connection(conn)
    inv = inventory(conn)
    checks = run_checks(conn)
    conn.close()

    checks.to_csv(cfg.REPORTS_DIR / "sql_validation_checks.csv", index=False)
    c = checks.status.value_counts().to_dict()
    lines = [
        "# Phase 4 - MySQL Validation Report", "",
        f"_Generated by `python/04b_validate_mysql.py` on {datetime.now():%Y-%m-%d %H:%M} against the **live MySQL server** "
        "(not a simulation). Credentials are read from the environment and never written to reports._", "",
        "## Connection", "",
        md_table(pd.DataFrame([info])), "",
        f"## Data-quality checks: **{c.get('PASS', 0)} PASS | {c.get('FAIL', 0)} FAIL** (of {len(checks)})", "",
        "Source: `sql/05_data_quality_checks.sql`. Each check computes its PASS/FAIL status inside MySQL.", "",
        md_table(checks), "",
        "## Server inventory (from information_schema)", "",
        "### Exact row counts", "", md_table(inv["row_counts"]), "",
        "### Tables and views", "", md_table(inv["tables"]), "",
        "### Foreign keys", "", md_table(inv["foreign_keys"]), "",
        "### Indexes", "", md_table(inv["indexes"]), "",
        "### CHECK constraints", "", md_table(inv["check_constraints"]), "",
    ]
    (cfg.REPORTS_DIR / "sql_validation_report.md").write_text("\n".join(lines), encoding="utf-8")

    print("CONNECTION:", info)
    print("\nROW COUNTS:\n" + inv["row_counts"].to_string(index=False))
    print(f"\nVIEWS: {', '.join(inv['tables'][inv['tables'].TABLE_TYPE == 'VIEW'].TABLE_NAME)}")
    print(f"FOREIGN KEYS: {len(inv['foreign_keys'])} | INDEXES: {len(inv['indexes'])} | "
          f"CHECK CONSTRAINTS: {len(inv['check_constraints'])}")
    print("\n" + checks.to_string(index=False, max_colwidth=70))
    print(f"\nPASS={c.get('PASS', 0)} FAIL={c.get('FAIL', 0)}")
    if c.get("FAIL", 0):
        sys.exit(1)


if __name__ == "__main__":
    main()
